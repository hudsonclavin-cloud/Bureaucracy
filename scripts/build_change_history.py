#!/usr/bin/env python
"""What changed since the last published graph, the change budget's verdict,
and the review queue.

    python scripts/build_change_history.py --dry-run           # the entry's summary and the budget, writes nothing
    python scripts/build_change_history.py --record            # append the entry, rewrite the queue, render the docs
    python scripts/build_change_history.py --before PATH       # compare against a graph file instead of the committed one

The BEFORE graph is the committed `output/graph.json` (`git show HEAD:...`) by
default: what the site served before this build. The AFTER graph is the one
just built in `output/`. `data_pipeline/changes.diff_graphs` reads the
difference node by node; `--record` prepends the entry to
`output/change_history.json` (served to the site's "What changed" card),
rewrites `data/audit/review_queue.json` (one record per held change or open
disagreement, with both documents; a vanished condition is closed, never
deleted; a person's `resolved` status survives), and renders
`docs/CHANGE_HISTORY.md`.

The exit code carries the budget: 0 within the budget, 3 when a rule tripped
and the build must be HELD -- the update job reads it and does not publish.
Nothing here fetches, and nothing here changes a graph.
"""

from __future__ import annotations

import argparse
import json
import subprocess
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from data_pipeline import changes as ch  # noqa: E402

DEFAULT_AFTER = PROJECT_ROOT / "output" / "graph.json"
DEFAULT_STATS = PROJECT_ROOT / "output" / "pipeline_stats.json"
DEFAULT_DOC = PROJECT_ROOT / "docs" / "CHANGE_HISTORY.md"
EXIT_HELD = 3
#: Entries kept whole in the served file; older ones keep their summary and
#: budget and drop their per-node lists, so the file stays small.
FULL_ENTRIES = 6


def committed_graph(ref: str = "HEAD") -> dict | None:
    try:
        out = subprocess.run(["git", "-C", str(PROJECT_ROOT), "show", f"{ref}:output/graph.json"], check=True, capture_output=True, text=True).stdout
    except (subprocess.CalledProcessError, OSError):
        return None
    return json.loads(out)


def built_at_of(stats_path: Path, after: dict) -> str | None:
    stats = ch.load_json(stats_path, {})
    stamp = str(stats.get("timestamp") or "")
    return stamp or None


def trim(entry: dict) -> dict:
    """An older entry keeps what a reader scans and drops the per-node lists."""
    keep = {k: entry[k] for k in ("builtAt", "anchor", "summary", "budget") if k in entry}
    keep["nodes"] = {k: entry["nodes"][k] for k in ("before", "after") if k in entry.get("nodes", {})}
    keep["measuredCosts"] = {k: entry["measuredCosts"][k] for k in ("before", "after") if k in entry.get("measuredCosts", {})}
    keep["pay"] = {k: entry["pay"][k] for k in ("claimsBefore", "claimsAfter") if k in entry.get("pay", {})}
    keep["counts"] = {
        "added": len(entry["nodes"].get("added", [])), "removed": len(entry["nodes"].get("removed", [])),
        "measuredMoved": len(entry["measuredCosts"].get("moved", [])), "payAdded": len(entry["pay"].get("added", [])),
        "payWithdrawn": len(entry["pay"].get("withdrawn", [])), "methodsWithdrawn": len(entry["evidence"].get("withdrawn", [])),
        "touched": len(entry.get("touched", [])),
    }
    keep["trimmed"] = True
    return keep


def render(history: list[dict], queue: list[dict]) -> str:
    out: list[str] = []
    w = out.append
    w("# Change history — what each build changed, and the review queue")
    w("")
    w("Generated by `python scripts/build_change_history.py --record` from the committed graph,")
    w("the graph just built, `output/change_history.json` and `data/audit/review_queue.json`.")
    w("Do not edit by hand. `docs/DEFINITION_OF_DONE.md` Part 2 (\"Change history\"), criterion 5")
    w("(the change budget) and criterion 7 (the review queue).")
    w("")
    open_records = [r for r in queue if r.get("status") == "open"]
    w(f"**Review queue: {len(open_records)} open**, {sum(1 for r in queue if r.get('status') == 'resolved')} resolved, "
      f"{sum(1 for r in queue if r.get('status') == 'closed')} closed. The queue is the only thing a person is asked to look at between cycles.")
    w("")
    by_kind: dict[str, list[dict]] = {}
    for r in open_records:
        by_kind.setdefault(str(r.get("kind")), []).append(r)
    for kind in ch.QUEUE_KINDS:
        records = by_kind.get(kind) or []
        if not records:
            continue
        w(f"### Open: `{kind}` ({len(records)})")
        w("")
        for r in records[:60]:
            who = f" — {r['nodeName']} (`{r['nodeId']}`)" if r.get("nodeId") else ""
            w(f"- opened {r['opened']}{who}: {r['detail']}")
            for d in r.get("documents") or []:
                w(f"  - {d.get('role')}: {d.get('says')}" + (f" — {d['url']}" if d.get("url") else ""))
        if len(records) > 60:
            w(f"- … and {len(records) - 60} more of this kind in `data/audit/review_queue.json`")
        w("")
    w("## Builds, newest first")
    w("")
    for entry in history:
        budget = entry.get("budget") or {}
        verdict = "**HELD**" if budget.get("held") else "within the budget"
        w(f"### {entry.get('builtAt')} — {verdict}")
        w("")
        w(entry.get("summary", ""))
        w("")
        for rule in budget.get("rules") or []:
            w(f"- `{rule['rule']}`: {'TRIPPED' if rule['tripped'] else 'ok'} — {rule['detail']}")
        w("")
        if entry.get("trimmed"):
            continue
        m = entry["measuredCosts"]
        if m.get("moved"):
            w("Measured costs that moved (largest first):")
            w("")
            for x in m["moved"][:25]:
                w(f"- {x['name']} (`{x['id']}`): ${x['before']:,.2f} → ${x['after']:,.2f} ({x['percent']}%)")
            w("")
        for label, items in (("Nodes added", entry["nodes"].get("added")), ("Nodes removed", entry["nodes"].get("removed")),
                             ("Nodes newly marked replaced", entry["nodes"].get("newlySuperseded")), ("Nodes renamed", entry["nodes"].get("renamed"))):
            if items:
                w(f"{label} ({len(items)}):")
                w("")
                for x in items[:40]:
                    w(f"- {x.get('name') or x.get('after')} (`{x['id']}`)" + (f": {x['before']} → {x['after']}" if "before" in x and "after" in x and "name" not in x else ""))
                if len(items) > 40:
                    w(f"- … and {len(items) - 40} more")
                w("")
        p = entry["pay"]
        for label, items in (("Pay claims added", p.get("added")), ("Pay claims withdrawn", p.get("withdrawn")), ("Pay figures changed", p.get("moved"))):
            if items:
                w(f"{label} ({len(items)}):")
                w("")
                for x in items[:40]:
                    w(f"- {x['name']} (`{x['id']}`), `{x['field']}`" + (f": {x['why']}" if x.get("why") else "") + (f": {x['before']} → {x['after']}" if "before" in x else ""))
                if len(items) > 40:
                    w(f"- … and {len(items) - 40} more")
                w("")
        e = entry["evidence"]
        for label, items in (("Methods withdrawn", e.get("withdrawn")), ("Methods added", e.get("added"))):
            if items:
                w(f"{label} ({len(items)}):")
                w("")
                for x in items[:40]:
                    w(f"- {x['name']} (`{x['id']}`), `{x['field']}` {x['method']}" + (f": {x['why']}" if x.get("why") else ""))
                if len(items) > 40:
                    w(f"- … and {len(items) - 40} more")
                w("")
        if entry["sources"].get("changed"):
            w("Sources whose copy changed:")
            w("")
            for x in entry["sources"]["changed"]:
                w(f"- `{x['id']}`: {x['before'] or '—'} → {x['after']} ({x['status']})")
            w("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--before", type=Path, default=None, help="a graph file to compare against; default: the committed output/graph.json")
    parser.add_argument("--before-ref", default="HEAD", help="the git ref whose output/graph.json is the BEFORE graph (default HEAD)")
    parser.add_argument("--after", type=Path, default=DEFAULT_AFTER)
    parser.add_argument("--history", type=Path, default=ch.HISTORY_PATH)
    parser.add_argument("--queue", type=Path, default=ch.QUEUE_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_DOC)
    parser.add_argument("--stats", type=Path, default=DEFAULT_STATS)
    parser.add_argument("--record", action="store_true", help="write the history entry, the queue and the document")
    parser.add_argument("--dry-run", action="store_true", help="print the summary and the budget; write nothing")
    args = parser.parse_args((argv or sys.argv)[1:])

    if not args.after.exists():
        print(f"refused: {args.after} does not exist")
        return 1
    after = json.loads(args.after.read_text(encoding="utf-8"))
    if args.before is not None:
        before = json.loads(args.before.read_text(encoding="utf-8"))
        before_label = str(args.before)
    else:
        before = committed_graph(args.before_ref)
        before_label = f"{args.before_ref}:output/graph.json"
        if before is None:
            print(f"refused: no committed graph at {before_label}")
            return 1
    entry = ch.diff_graphs(before, after, built_at=built_at_of(args.stats, after))
    entry["before"] = before_label
    print(entry["summary"])
    for rule in entry["budget"]["rules"]:
        print(f"  {'TRIPPED' if rule['tripped'] else 'ok     '} {rule['rule']}: {rule['detail']}")
    if entry["measuredCosts"]["forReview"]:
        print(f"  for review: {len(entry['measuredCosts']['forReview'])} measured costs moved by more than {ch.MEASURED_REVIEW_MOVE:.0%} between statements")
    history = ch.load_json(args.history, [])
    history = history if isinstance(history, list) else []
    previous_queue = ch.load_json(args.queue, [])
    previous_queue = previous_queue if isinstance(previous_queue, list) else []
    queue = ch.review_queue(entry, after, previous_queue, today=entry["builtAt"][:10])
    open_count = sum(1 for r in queue if r.get("status") == "open")
    entry["reviewQueueOpen"] = open_count
    print(f"review queue: {open_count} open ({sum(1 for r in queue if r.get('status') == 'open' and r.get('key') not in {q.get('key') for q in previous_queue})} new), "
          f"{sum(1 for r in queue if r.get('status') == 'closed')} closed, {sum(1 for r in queue if r.get('status') == 'resolved')} resolved")
    if args.dry_run or not args.record:
        return EXIT_HELD if entry["budget"]["held"] else 0
    # The same build recorded twice (a re-run of the job on an unchanged
    # graph) replaces its own entry rather than stacking a duplicate.
    history = [h for h in history if h.get("builtAt") != entry["builtAt"]]
    history.insert(0, entry)
    history = [h if i < FULL_ENTRIES or h.get("trimmed") else trim(h) for i, h in enumerate(history)]
    args.history.parent.mkdir(parents=True, exist_ok=True)
    args.history.write_text(json.dumps(history, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    args.queue.parent.mkdir(parents=True, exist_ok=True)
    args.queue.write_text(json.dumps(queue, indent=1, ensure_ascii=False) + "\n", encoding="utf-8")
    args.out.write_text(render(history, queue), encoding="utf-8")
    print(f"wrote {args.history.relative_to(PROJECT_ROOT)}, {args.queue.relative_to(PROJECT_ROOT)}, {args.out.relative_to(PROJECT_ROOT)}")
    return EXIT_HELD if entry["budget"]["held"] else 0


if __name__ == "__main__":
    sys.exit(main())
