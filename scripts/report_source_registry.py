#!/usr/bin/env python
"""The source registry, rendered: each source's cycle, the copy in use, what is
due, and the status as of today.

    python scripts/report_source_registry.py --dry-run   # the table, writes nothing
    python scripts/report_source_registry.py             # writes docs/SOURCE_REGISTRY.md
    python scripts/report_source_registry.py --due       # only the sources due or overdue (the update job's list)

`docs/DEFINITION_OF_DONE.md` criterion 6. `data/source_registry.json` is the
reviewed table; `data_pipeline/freshness.py` re-derives every date against the
published graph and the fixtures' own fetch records; the exporter stamps the
result on the graph root as `__sourceRegistry`, and this script prints the same
derivation as a document. Nothing here fetches.
"""

from __future__ import annotations

import argparse
import json
import sys
from datetime import date
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from data_pipeline import freshness as fr  # noqa: E402

DEFAULT_GRAPH = PROJECT_ROOT / "output" / "graph.json"
DEFAULT_DOC = PROJECT_ROOT / "docs" / "SOURCE_REGISTRY.md"
STATUS_TEXT = {
    fr.STATUS_CURRENT: "current",
    fr.STATUS_EXPECTED: "a newer edition is expected and not yet in use",
    fr.STATUS_OVERDUE: "**OVERDUE**",
    fr.STATUS_RECHECK: "a re-check is due",
    fr.STATUS_CLOSED: "closed record",
    fr.STATUS_UNKNOWN: "copy date not read",
}


def field_text(spec) -> str:
    """One graphFields entry in words: the field, scoped where the entry is."""
    if isinstance(spec, str):
        return spec
    if "costStatus" in spec:
        return "cost_status " + "/".join(spec["costStatus"])
    if "nodeWhere" in spec:
        return "node " + "/".join(str(path) for path, _wanted in spec["nodeWhere"])
    where = spec.get("where") or []
    return str(spec.get("field")) + ("" if not where else " where " + ", ".join(f"{path}={wanted if isinstance(wanted, str) else wanted}" for path, wanted in where))


def due_sources(block: dict) -> list[dict]:
    """What the update job would try this cycle: every source whose status is
    not `current` or `closed_record`."""
    return [e for e in block["sources"] if e["statusAtBuild"] not in (fr.STATUS_CURRENT, fr.STATUS_CLOSED)]


def render(block: dict, refused: list[dict]) -> str:
    out: list[str] = []
    w = out.append
    w("# Source registry — each source's cycle, the copy in use, and what is due")
    w("")
    w(f"Generated by `python scripts/report_source_registry.py` from `data/source_registry.json`,")
    w("the fixtures' own fetch records and `output/graph.json`, as of the build date below.")
    w("Do not edit by hand; regenerate it. `tests/test_source_registry.py` re-renders it and pins")
    w("the module and the gate equal.")
    w("")
    w(f"`docs/DEFINITION_OF_DONE.md` criterion 6. As of **{block['asOf']}**: " + ", ".join(
        f"{v} {k.replace('_', ' ')}" for k, v in block["counts"].items() if v) + ".")
    w("")
    w(f"Cadences are {block['cadencesAre']}.")
    w("")
    if refused:
        w("## Rows refused on re-adjudication")
        w("")
        for row in refused:
            w(f"- `{row['id']}`: {'; '.join(row['problems'])}")
        w("")
    due = due_sources(block)
    w("## Due now")
    w("")
    if due:
        for e in due:
            w(f"- `{e['id']}` — {STATUS_TEXT[e['statusAtBuild']]}: copy dated {e['copy']['date']}" + (
                f", the edition for {e['expected']['next']} expected by {e['expected']['expectedBy']}" if e["expected"].get("expectedBy") else
                f", re-check due after {e['expected']['recheckDue']}" if e["expected"].get("recheckDue") else "") + (
                "; last read after the expected date" if e.get("lastReadAfterExpected") else ""))
    else:
        w("- nothing")
    w("")
    w("## Every source")
    w("")
    w("| source | publisher | cycle | copy in use | read | next edition | expected by | overdue after | re-check due | status | fixtures | fields |")
    w("|---|---|---|---|---|---|---|---|---|---|---|---|")
    for e in block["sources"]:
        x = e["expected"]
        fields = ", ".join(field_text(s) for s in e["graphFields"])
        w(f"| `{e['id']}` {e['label']} | {e['publisher']} | {e['cadence']['text']} | {e['copy']['date'] or '—'} ({e['copy']['meaning']}) | {e['copy']['fetchedAt'] or '—'} | "
          f"{x['next'] or '—'} | {x['expectedBy'] or '—'} | {x['overdueAfter'] or '—'} | {x['recheckDue'] or '—'} | {STATUS_TEXT[e['statusAtBuild']]} | {e['fixtureCount']} | {fields} |")
    w("")
    w("## How each next copy would be fetched")
    w("")
    for e in block["sources"]:
        f = e["fetch"]
        w(f"- `{e['id']}`: `{f['kind']}`" + (f" — {f['url']}" if f.get("url") else "") + f". Cycle basis: {e['cadence'].get('basis', '')}" + (f" {e['note']}" if e.get("note") else ""))
    w("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--graph", type=Path, default=DEFAULT_GRAPH)
    parser.add_argument("--registry", type=Path, default=fr.REGISTRY_PATH)
    parser.add_argument("--out", type=Path, default=DEFAULT_DOC)
    parser.add_argument("--as-of", type=date.fromisoformat, default=None, help="the date to judge status at; default: the graph's own __sourceRegistry.asOf, else today")
    parser.add_argument("--dry-run", action="store_true")
    parser.add_argument("--due", action="store_true", help="print the due sources as JSON and nothing else")
    args = parser.parse_args((argv or sys.argv)[1:])
    if not args.graph.exists():
        print(f"refused: {args.graph} does not exist")
        return 1
    graph = json.loads(args.graph.read_text(encoding="utf-8"))
    published = graph.get(fr.ROOT_FIELD) if isinstance(graph.get(fr.ROOT_FIELD), dict) else {}
    as_of = args.as_of or fr.parse_date(published.get("asOf")) or fr.today_utc()
    block, refused = fr.derive(graph, fr.load_registry(args.registry), as_of)
    if args.due:
        print(json.dumps(due_sources(block), indent=1))
        return 0
    for e in block["sources"]:
        print(f"{e['id']:34} {e['statusAtBuild']:24} copy {e['copy']['date'] or '—':10} next {e['expected']['next'] or '—':10} by {e['expected']['expectedBy'] or e['expected']['recheckDue'] or '—'}")
    print(f"as of {block['asOf']}: {block['counts']}; refused {len(refused)}")
    if args.dry_run:
        return 0
    args.out.write_text(render(block, refused), encoding="utf-8")
    print(f"wrote {args.out.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
