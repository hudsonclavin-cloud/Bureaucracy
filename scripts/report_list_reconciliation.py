#!/usr/bin/env python
"""The government's own lists reconciled against the graph, as one number.

    python scripts/report_list_reconciliation.py --dry-run   # the counts, writes nothing
    python scripts/report_list_reconciliation.py             # writes docs/LIST_RECONCILIATION.md

`docs/DEFINITION_OF_DONE.md` criterion 4(a): every unit on the Government
Manual's entries, the Federal Register agency directory, USAspending's toptier
agencies, the two chambers' committee lists and the current Plum Book's
agencies is a node or is recorded as deliberately not one; every curated
committee name a complete list lacks is resolved. `data/curation/
list_dispositions.json` is the record and `data_pipeline/verification/
list_dispositions.py` re-adjudicates it against the committed lists on every
run. This script renders the result and prints the gap as one number:

    gap = unmatched entries with no accepted disposition, or disposed `unsure`
        + real units the lists name that the graph has not added (distinct)
        + curated names no accepted row resolves

The second term is counted on purpose: a unit recorded as "not added, here is
the route" is neither a node nor deliberately not one, so the definition's own
words put it in the gap.

Nothing here fetches, and nothing here writes to the curated file, the
published graph or any evidence file.
"""

from __future__ import annotations

import argparse
import json
import sys
from pathlib import Path

PROJECT_ROOT = Path(__file__).resolve().parents[1]
if str(PROJECT_ROOT) not in sys.path:
    sys.path.insert(0, str(PROJECT_ROOT))

from data_pipeline.exporter.build_graph import canonical_name_key  # noqa: E402
from data_pipeline.verification import list_dispositions as ld  # noqa: E402

DEFAULT_GRAPH = PROJECT_ROOT / "output" / "graph.json"
DEFAULT_DOC = PROJECT_ROOT / "docs" / "LIST_RECONCILIATION.md"

KIND_TEXT = {
    "scaffolding": "the list's own grouping heading",
    "distinct_from_the_graphs_unit": "a different unit from the graph's, by population",
    "carried_as_a_post": "carried as its head's post",
    "names_a_node_under_another_wording": "names a node under another wording",
    "carried_outside_the_lists_scope": "a node outside the subtree the list's matcher is scoped to",
    "predecessor_of_a_node": "a former unit whose functions a node holds",
    "former_body": "a body that no longer exists",
    "unit_beneath_a_node_not_drawn": "a live office beneath a node, not drawn",
    "umbrella_body_drawn_as_its_members": "a statutory umbrella drawn as its members",
    "body_outside_the_graphs_scope": "an advisory, interagency or temporary body outside the graph's scope",
    "non_federal_or_international_body": "not a unit of the federal government",
    "fund_or_account_not_a_unit": "an account or fund, not a unit",
    "unit_the_list_names_not_added": "a real unit the graph lacks, recorded with its route (addable)",
    "unsure": "left unsure (unresolved)",
    "kept_the_committees_own_wording": "kept the committee's own wording",
    "former_seat_kept_as_a_record": "a former seat kept as a record",
    "successor_is_a_sibling_merge_lead": "its successor is already a sibling; a merge lead",
}


def distinct_addable(result: dict) -> dict[str, list[str]]:
    """Addable units by canonical name, with the lists that name each."""
    out: dict[str, list[str]] = {}
    for item in result["lists"]:
        for entry in item["addable"]:
            row = item["rows"].get(entry) or {}
            # a row may carry `unitKey`, the one key three lists' spellings of
            # one unit share; without it the canonical name is the key
            key = str(row.get("unitKey") or canonical_name_key(entry.split(" :: ")[-1]))
            out.setdefault(key, []).append(f"{item['id']}: {entry}")
    return out


def gap_terms(result: dict) -> dict[str, int]:
    unresolved = sum(len(item["unresolved"]) for item in result["lists"])
    curated = sum(len(item["curatedUnresolved"]) for item in result["lists"])
    addable = len(distinct_addable(result))
    return {"unresolvedEntries": unresolved, "addableUnits": addable, "curatedUnresolved": curated,
            "gap": unresolved + addable + curated}


def render(result: dict) -> str:
    out: list[str] = []
    w = out.append
    terms = gap_terms(result)
    w("# List reconciliation — the government's own lists against the graph")
    w("")
    w("Generated by `python scripts/report_list_reconciliation.py` from `output/graph.json`,")
    w("the committed list fixtures and `data/curation/list_dispositions.json`. Do not edit")
    w("by hand; regenerate it. `tests/test_list_reconciliation.py` re-renders it and asserts")
    w("the dispositions re-adjudicate.")
    w("")
    w("`docs/DEFINITION_OF_DONE.md` criterion 4(a): every unit on five official lists is a")
    w("node or recorded as deliberately not one, and every curated committee name a complete")
    w("list lacks is resolved. The gap, as one number:")
    w("")
    w(f"- **criterion 4(a) gap: {terms['gap']}** = {terms['unresolvedEntries']} list entries unresolved "
      f"+ {terms['addableUnits']} distinct real units the lists name and the graph has not added "
      f"+ {terms['curatedUnresolved']} curated committee names unresolved")
    w(f"- rows refused on re-adjudication: {len(result['refused'])}")
    w("")
    w("| list | version | entries | reach a node | disposed | unresolved | addable | curated names the list lacks | of them unresolved |")
    w("|---|---|---|---|---|---|---|---|---|")
    for item in result["lists"]:
        w(f"| {item['label']} | {item['version']} | {item['entries']:,} | {item['matched']:,} | {item['disposed']:,} | "
          f"{len(item['unresolved'])} | {len(item['addable'])} | {item['curatedNamesNotInList']} | {len(item['curatedUnresolved'])} |")
    w("")
    w("A disposition's basis ending \"Reviewer's statement\" rests on the reviewer's knowledge and")
    w("no committed document; a row with a quote rests on the list's own words, re-found on")
    w("every run. `unit_the_list_names_not_added` is a real unit recorded with the route that")
    w("would add it, counted in the gap and never as reconciled.")
    w("")
    if result["refused"]:
        w("## Rows refused on re-adjudication")
        w("")
        for row in result["refused"]:
            w(f"- `{row['list']}` — {row['entry']} (`{row['disposition']}`): {row['reason']}")
        w("")
    addable = distinct_addable(result)
    if addable:
        w("## Real units the lists name and the graph has not added")
        w("")
        w("Each is counted once in the gap however many lists name it.")
        w("")
        for key in sorted(addable):
            w(f"- {addable[key][0].split(': ', 1)[1]} — named by {len(addable[key])} list(s): " + "; ".join(f"`{x.split(':')[0]}`" for x in addable[key]))
        w("")
    for item in result["lists"]:
        w(f"## {item['label']}")
        w("")
        w(f"{item['entries']:,} entries ({item['version']}); {item['matched']:,} reach a node by the list's own matcher; "
          f"{item['unmatched']:,} do not, of which {item['disposed']:,} carry an accepted disposition.")
        w("")
        if item["byKind"]:
            w("| disposition | entries |")
            w("|---|---|")
            for kind, count in item["byKind"].items():
                w(f"| `{kind}` — {KIND_TEXT.get(kind, kind)} | {count} |")
            w("")
        if item["unresolved"]:
            w("**Unresolved:**")
            w("")
            for entry in item["unresolved"]:
                row = item["rows"].get(entry)
                w(f"- {entry}" + (f" — `unsure`: {row['basis']}" if row else " — no disposition recorded"))
            w("")
        if item["addable"]:
            w("**Real units the graph lacks (addable):**")
            w("")
            for entry in item["addable"]:
                w(f"- {entry} — {item['rows'][entry]['basis']}")
            w("")
        disposed = [(entry, row) for entry, row in sorted(item["rows"].items()) if row["disposition"] not in ("unsure", "unit_the_list_names_not_added")]
        if disposed:
            w("<details><summary>Every other disposition, entry by entry</summary>")
            w("")
            for entry, row in disposed:
                extra = []
                if row.get("nodeId"):
                    extra.append(f"node `{row['nodeId']}`")
                if row.get("parentNodeId"):
                    extra.append(f"beneath `{row['parentNodeId']}`")
                if row.get("quote"):
                    extra.append(f"the list's words: \"{row['quote']}\"")
                w(f"- {entry} — `{row['disposition']}`" + (f" ({'; '.join(extra)})" if extra else "") + f": {row['basis']}")
            w("")
            w("</details>")
            w("")
        if item["curatedNamesNotInList"]:
            w(f"**Curated names this complete list does not carry ({item['curatedNamesNotInList']}):**")
            w("")
            for node_id, context in sorted(item["curatedContext"].items(), key=lambda kv: kv[1]["name"]):
                row = item["curatedRows"].get(node_id)
                where = f" under {context['committee']}" if context.get("committee") else ""
                if row:
                    w(f"- {context['name']}{where} (`{node_id}`) — `{row['disposition']}`: {row['basis']}")
                else:
                    w(f"- {context['name']}{where} (`{node_id}`) — **unresolved**: no disposition recorded")
            w("")
    return "\n".join(out) + "\n"


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--graph", type=Path, default=DEFAULT_GRAPH)
    parser.add_argument("--table", type=Path, default=ld.DEFAULT_TABLE)
    parser.add_argument("--out", type=Path, default=DEFAULT_DOC)
    parser.add_argument("--dry-run", action="store_true", help="print the counts and write nothing")
    args = parser.parse_args((argv or sys.argv)[1:])
    if not args.graph.exists():
        print(f"refused: {args.graph} does not exist")
        return 1
    graph = json.loads(args.graph.read_text(encoding="utf-8"))
    result = ld.adjudicate(graph, ld.load_table(args.table))
    terms = gap_terms(result)
    for item in result["lists"]:
        print(f"{item['id']:30} entries {item['entries']:4,}  reach a node {item['matched']:4,}  unmatched {item['unmatched']:4,}  "
              f"disposed {item['disposed']:4,}  unresolved {len(item['unresolved']):3}  addable {len(item['addable']):3}  "
              f"curated lacking {item['curatedNamesNotInList']:3} (unresolved {len(item['curatedUnresolved'])})")
    print(f"rows refused: {len(result['refused'])}")
    for row in result["refused"]:
        print(f"  {row['list']} | {row['entry']} | {row['disposition']} | {row['reason']}")
    print(f"criterion 4(a) gap: {terms['gap']} = {terms['unresolvedEntries']} unresolved entries + {terms['addableUnits']} distinct addable units + {terms['curatedUnresolved']} curated names unresolved")
    if args.dry_run:
        return 0
    args.out.write_text(render(result), encoding="utf-8")
    print(f"wrote {args.out.relative_to(PROJECT_ROOT)}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
